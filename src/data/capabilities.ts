function buildCapability(spec: CapabilitySpec): Capability {
  const available = spec.available !== false;
  if (!available) {
    return {
      id: spec.id,
      name: spec.name,
      subtitle: spec.subtitle,
      navGroup: spec.navGroup,
      available: false,
      features: [],
      configs: [],
      prerequisites: [],
      codeNotes: spec.codeNotes ?? [],
      detailed: false,
      unavailableReason: spec.unavailableReason,
    };
  }

  const masterState: ToggleState = spec.live ? 'live' : 'off';
  const master: Feature = {
    key: spec.id,
    label: spec.masterLabel,
    state: masterState,
    description: spec.masterDescription,
  };

  const subFeatures: Feature[] = (spec.subFeatures ?? []).map((feature) => ({
    key: feature.key,
    label: feature.label,
    description: feature.description,
    prerequisiteKey: spec.id,
    // Dependents follow the master unless the spec pins them.
    state: feature.state ?? (spec.live ? 'live' : 'off'),
  }));

  return {
    id: spec.id,
    name: spec.name,
    subtitle: spec.subtitle,
    navGroup: spec.navGroup,
    available: true,
    masterFeatureKey: spec.id,
    features: [master, ...subFeatures],
    configs: spec.configs ?? [],
    prerequisites: [masterToggleCheck(spec), ...(spec.prerequisites ?? [])],
    codeNotes: spec.codeNotes ?? [],
    detailed: true,
  };
}

