/** Shorthand for a config field, so the data below stays readable. */
function cfg(field: Omit<ConfigField, 'state'> & { state?: ConfigField['state'] }): ConfigField {
  return { state: 'saved', ...field };
}

/** Config groups in the order the fields declare them. */
export function configGroups(fields: ConfigField[]): string[] {
  const groups: string[] = [];
  for (const field of fields) if (!groups.includes(field.group)) groups.push(field.group);
  return groups;
}

