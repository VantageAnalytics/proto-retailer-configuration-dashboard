type CapabilitySpec = {
  id: string;
  name: string;
  subtitle?: string;
  navGroup: string;
  live?: boolean;
  available?: boolean;
  unavailableReason?: string;
  masterLabel: string;
  masterDescription: string;
  /** Features gated behind the master toggle. */
  subFeatures?: { key: string; label: string; description: string; state?: ToggleState }[];
  configs?: ConfigField[];
  prerequisites?: PrerequisiteCheck[];
  codeNotes?: string[];
};

/** The flag check that every capability shares, named so status.ts can skip it. */
function masterToggleCheck(spec: CapabilitySpec): PrerequisiteCheck {
  return {
    key: `${spec.id}-toggle`,
    label: `${spec.id} toggle is on`,
    passed: Boolean(spec.live),
    source: 'LaunchDarkly',
    explanation: spec.live
      ? 'Flag is on in LaunchDarkly for this retailer.'
      : `Turn ${spec.masterLabel} on below to request the flag.`,
  };
}

